#!/usr/bin/env node
// Generates supabase/tests/grading.test.sql from the shared grading fixtures so that
// public.grading_normalize / public.grade_exercise (SQL) and normalizeAnswer / gradeResponse (TS)
// are verified against the same cases.
// Usage: node scripts/sync-grading-fixtures.mjs [--check]
// GRADING_FIXTURES / GRADING_OUT override the input and output paths (used by the tests).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FIXTURES = process.env.GRADING_FIXTURES || join(root, 'packages', 'shared', 'src', 'content', 'grading.fixtures.json');
const OUT = process.env.GRADING_OUT || join(root, 'supabase', 'tests', 'grading.test.sql');

// Mirrors DEFAULT_RUBRIC in packages/shared/src/content/exercises.ts.
const DEFAULT_RUBRIC = {
  punctuation: 'ignore',
  diacritics: 'strict',
  ko_spacing: 'lenient',
  typo_tolerance: 0,
  expand_contractions: true,
};
const SCORES = { correct: 1, almost: 0.8, incorrect: 0 };

const fixtures = JSON.parse(readFileSync(FIXTURES, 'utf8'));
const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`;
const lines = [];
let count = 0;
const test = (sql) => {
  lines.push(sql);
  count++;
};

for (const c of fixtures.normalize) {
  const rubric = { ...DEFAULT_RUBRIC, ...(c.rubric ?? {}) };
  test(
    `select is(public.grading_normalize(${lit(c.input)}, ${lit(c.lang)}, ${json(rubric)}), ${lit(c.expected)}, ${lit(`normalize: ${c.name}`)});`,
  );
}

for (const c of fixtures.grade) {
  const rubric = { ...DEFAULT_RUBRIC, ...(c.rubric ?? {}) };
  if (!(c.expected.verdict in SCORES)) throw new Error(`Fixture "${c.name}": unknown verdict ${c.expected.verdict}`);
  const expected = {
    verdict: c.expected.verdict,
    score: SCORES[c.expected.verdict],
    error_tags: c.expected.error_tags,
    feedback_vi: c.expected.feedback_vi,
  };
  test(
    `select is(public.grade_exercise(${lit(c.type)}, ${json(c.answer)}, ${json(rubric)}, ${json(c.known_wrong ?? [])}, ${lit(c.lang)}, ${json(c.response)}), ${json(expected)}, ${lit(`grade: ${c.name}`)});`,
  );
}

const sql = [
  '-- GENERATED by scripts/sync-grading-fixtures.mjs from packages/shared/src/content/grading.fixtures.json.',
  '-- Do not edit by hand: run `pnpm fixtures:grading`.',
  'begin;',
  'create extension if not exists pgtap with schema extensions;',
  `select plan(${count});`,
  ...lines,
  'select * from finish();',
  'rollback;',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replaceAll('\r\n', '\n') : '';
  if (current !== sql) {
    console.error('::error::supabase/tests/grading.test.sql is out of date. Run `pnpm fixtures:grading` and commit.');
    process.exit(1);
  }
  console.log('Grading fixtures in sync.');
} else {
  writeFileSync(OUT, sql);
  console.log(`Wrote ${OUT} (${count} assertions).`);
}
