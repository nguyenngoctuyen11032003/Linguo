import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const script = join(root, 'scripts', 'sync-exam-grading-fixtures.mjs');
const fixtures = join(root, 'packages', 'shared', 'src', 'exam', 'grading.fixtures.json');

const run = (args, env) => spawnSync(process.execPath, [script, ...args], { env: { ...process.env, ...env }, encoding: 'utf8' });

const withTmp = (fn) => {
  const dir = mkdtempSync(join(tmpdir(), 'exam-grading-fixtures-'));
  try {
    const fx = join(dir, 'fixtures.json');
    const out = join(dir, 'exam_grading.test.sql');
    fn({ fx, out, env: { EXAM_GRADING_FIXTURES: fx, EXAM_GRADING_OUT: out } });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
};

test('generates one assertion per case and --check detects drift', () => {
  withTmp(({ fx, out, env }) => {
    const data = [
      { input: '좋아요.', accepted: ['좋아요'], correct: true },
      { input: "I'm busy", accepted: ['I am busy'], correct: false },
    ];
    writeFileSync(fx, JSON.stringify(data));
    assert.equal(run([], env).status, 0);
    const sql = readFileSync(out, 'utf8');
    assert.match(sql, /^-- GENERATED by scripts\/sync-exam-grading-fixtures\.mjs/);
    // 2 fixture cases + 4 static assertions about the two-argument normaliser.
    assert.match(sql, /select plan\(6\);/);
    assert.match(sql, /^begin;$/m);
    assert.match(sql, /^rollback;\n$/m);
    assert.ok(
      sql.includes(
        "select is((public.exam_normalize_text('좋아요.') <> '' and exists (select 1 from unnest(array['좋아요']::text[]) as acc(t) where public.exam_normalize_text(acc.t) = public.exam_normalize_text('좋아요.'))), true,",
      ),
    );
    assert.ok(sql.includes("public.exam_normalize_text('I''m busy')"));
    assert.ok(sql.includes(', false, '));
    assert.equal(run(['--check'], env).status, 0);

    data[1].correct = true;
    writeFileSync(fx, JSON.stringify(data));
    const check = run(['--check'], env);
    assert.equal(check.status, 1);
    assert.match(check.stderr, /out of date/);
  });
});

test('a fixture language switches to the two-argument normaliser and is validated', () => {
  withTmp(({ fx, out, env }) => {
    writeFileSync(fx, JSON.stringify([{ language: 'de', input: 'fuer', accepted: ['für'], correct: true }]));
    assert.equal(run([], env).status, 0);
    const sql = readFileSync(out, 'utf8');
    assert.ok(
      sql.includes(
        "select is((public.exam_normalize_text('fuer', 'de') <> '' and exists (select 1 from unnest(array['für']::text[]) as acc(t) where public.exam_normalize_text(acc.t, 'de') = public.exam_normalize_text('fuer', 'de'))), true,",
      ),
    );
    assert.ok(sql.includes('short_text #1 [de]: "fuer" vs ["f\\u00fcr"]'));
    writeFileSync(fx, JSON.stringify([{ language: 'fr', input: 'a', accepted: ['a'], correct: true }]));
    const bad = run([], env);
    assert.notEqual(bad.status, 0);
    assert.match(bad.stderr, /language must be one of/);
  });
});

test('escapes control, space-like and NFD jamo characters as U& literals', () => {
  withTmp(({ fx, out, env }) => {
    writeFileSync(fx, JSON.stringify([{ input: '\t가　'.normalize('NFD'), accepted: ['가'], correct: true }]));
    assert.equal(run([], env).status, 0);
    const sql = readFileSync(out, 'utf8');
    assert.ok(sql.includes("U&'\\0009\\1100\\1161\\3000'"));
    // Labels stay ASCII.
    assert.ok(sql.includes('short_text #1: "\\t\\u1100\\u1161\\u3000" vs ["\\uac00"]'));
  });
});

test('rejects malformed fixtures', () => {
  withTmp(({ fx, env }) => {
    writeFileSync(fx, JSON.stringify([{ input: 'a', accepted: [], correct: true }]));
    const bad = run([], env);
    assert.notEqual(bad.status, 0);
    assert.match(bad.stderr, /accepted must be a non-empty string array/);
    writeFileSync(fx, JSON.stringify([{ input: 'a', accepted: ['a'], correct: 'yes' }]));
    assert.notEqual(run([], env).status, 0);
  });
});

test('the committed exam_grading.test.sql is in sync', { skip: !existsSync(fixtures) && 'grading.fixtures.json not present' }, () => {
  assert.equal(run(['--check'], {}).status, 0);
});
