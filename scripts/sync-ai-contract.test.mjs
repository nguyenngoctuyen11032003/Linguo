import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const script = join(root, 'scripts', 'sync-ai-contract.mjs');

const run = (args, env) => spawnSync(process.execPath, [script, ...args], { env: { ...process.env, ...env }, encoding: 'utf8' });

const withTmp = (fn) => {
  const dir = mkdtempSync(join(tmpdir(), 'ai-contract-'));
  try {
    const src = join(dir, 'contract.ts');
    const out = join(dir, 'nested', 'ai-contract.ts');
    fn({ src, out, env: { AI_CONTRACT_SRC: src, AI_CONTRACT_OUT: out } });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
};

const SAMPLE = "import { z } from 'zod';\n\nexport const a = z.string();\n";

test('copies the contract verbatim under a GENERATED header and --check detects drift', () => {
  withTmp(({ src, out, env }) => {
    writeFileSync(src, SAMPLE);
    assert.equal(run(['--check'], env).status, 1, 'a missing copy is out of date');
    assert.equal(run([], env).status, 0);
    const copy = readFileSync(out, 'utf8');
    assert.match(copy, /^\/\/ GENERATED by scripts\/sync-ai-contract\.mjs/);
    assert.ok(copy.endsWith(`\n\n${SAMPLE}`));
    assert.equal(run(['--check'], env).status, 0);

    writeFileSync(src, SAMPLE.replace('z.string()', 'z.number()'));
    const check = run(['--check'], env);
    assert.equal(check.status, 1);
    assert.match(check.stderr, /out of date/);
  });
});

test('normalises CRLF so --check passes on Windows checkouts', () => {
  withTmp(({ src, out, env }) => {
    writeFileSync(src, SAMPLE);
    assert.equal(run([], env).status, 0);
    writeFileSync(src, SAMPLE.replaceAll('\n', '\r\n'));
    writeFileSync(out, readFileSync(out, 'utf8').replaceAll('\n', '\r\n'));
    assert.equal(run(['--check'], env).status, 0);
  });
});

test('rejects imports other than zod', () => {
  withTmp(({ src, env }) => {
    writeFileSync(src, `${SAMPLE}import { x } from '../other';\n`);
    const res = run([], env);
    assert.equal(res.status, 1);
    assert.match(res.stderr, /may import only 'zod'/);
    writeFileSync(src, `${SAMPLE}export * from "./more";\n`);
    assert.equal(run([], env).status, 1);
  });
});

test('the committed supabase/functions/_shared/ai-contract.ts is in sync', () => {
  assert.equal(run(['--check'], {}).status, 0);
});
