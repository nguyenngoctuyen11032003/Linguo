import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const script = join(root, 'scripts', 'sync-diagnostic-fixtures.mjs');
const fixtures = join(root, 'packages', 'shared', 'src', 'diagnostic', 'engine.fixtures.json');

const run = (args, env) => spawnSync(process.execPath, [script, ...args], { env: { ...process.env, ...env }, encoding: 'utf8' });

const sample = () => ({
  posterior: [
    { name: 'prior only', prior: { mean: 1.5, sd: 1.25 }, answers: [], expected: { mean: 1.5, sd: 1.2, level: 1, range: { low: 0, high: 3 } } },
    {
      name: "two answers, it's",
      prior: { mean: 0.5, sd: 1.25 },
      answers: [
        { b: 0.5, options: 4, correct: true },
        { b: 1.5, options: 3, correct: false },
      ],
      expected: { mean: 0.75, sd: 0.9, level: 0, range: { low: 0, high: 2 } },
    },
  ],
  confidence: [{ name: 'rapid', sd: 0.4, n: 6, rapidShare: 0.35, expected: 'medium' }],
  suggest: [
    { name: 'two', skills: [{ level: 2, confidence: 'high' }, { level: 3, confidence: 'medium' }], expected: 2 },
    { name: 'one', skills: [{ level: 2, confidence: 'low' }, { level: 3, confidence: 'medium' }], expected: null },
  ],
  cap: [{ name: 'first', current: 1, suggested: 5, firstApplied: true, expected: 3 }],
  stop: [{ name: 'reading max', skill: 'reading', n: 5, sd: 0.9, bankLeft: 3, expected: true }],
});

const withTmp = (fn) => {
  const dir = mkdtempSync(join(tmpdir(), 'diagnostic-fixtures-'));
  try {
    const fx = join(dir, 'fixtures.json');
    const out = join(dir, 'diagnostic_engine.test.sql');
    fn({ fx, out, env: { DIAGNOSTIC_FIXTURES: fx, DIAGNOSTIC_OUT: out } });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
};

test('generates one assertion per checked value and --check detects drift', () => {
  withTmp(({ fx, out, env }) => {
    const data = sample();
    writeFileSync(fx, JSON.stringify(data));
    assert.equal(run([], env).status, 0);
    const sql = readFileSync(out, 'utf8');
    assert.match(sql, /^-- GENERATED by scripts\/sync-diagnostic-fixtures\.mjs/);
    // 4 per posterior case (mean, sd, level, range) + 1 per other case.
    assert.match(sql, /select plan\(13\);/);
    assert.match(sql, /^begin;$/m);
    assert.match(sql, /^rollback;\n$/m);
    assert.equal(run(['--check'], env).status, 0);

    data.posterior[1].expected.sd = 0.91;
    writeFileSync(fx, JSON.stringify(data));
    const check = run(['--check'], env);
    assert.equal(check.status, 1);
    assert.match(check.stderr, /out of date/);
  });
});

test('writes the SQL calls with typed arrays, tolerances and escaped labels', () => {
  withTmp(({ fx, out, env }) => {
    writeFileSync(fx, JSON.stringify(sample()));
    assert.equal(run([], env).status, 0);
    const sql = readFileSync(out, 'utf8');
    assert.ok(
      sql.includes(
        '  (1, public.diag_posterior(1.5, 1.25, array[]::double precision[], array[]::integer[], array[]::boolean[])),',
      ),
    );
    assert.ok(
      sql.includes(
        '  (2, public.diag_posterior(0.5, 1.25, array[0.5, 1.5]::double precision[], array[4, 3]::integer[], array[true, false]::boolean[]));',
      ),
    );
    assert.ok(
      sql.includes(
        `select ok((select abs((public.diag_eap(w)->>'sd')::double precision - 0.9) < 1e-6 from diag_posteriors where id = 2), 'posterior: two answers, it''s: sd');`,
      ),
    );
    assert.ok(sql.includes(`select is((select public.diag_conservative_level(w) from diag_posteriors where id = 1), 1, 'posterior: prior only: level');`));
    assert.ok(sql.includes(`'{"low": 0, "high": 3}'::jsonb, 'posterior: prior only: range');`));
    assert.ok(sql.includes(`select is(public.diag_confidence(0.4, 6, 0.35), 'medium', 'confidence: rapid');`));
    assert.ok(sql.includes(`select is(public.diag_suggest_level(array[2, 3]::integer[], array['high', 'medium']::text[]), 2, 'suggest: two');`));
    assert.ok(sql.includes(`array['low', 'medium']::text[]), null::integer, 'suggest: one');`));
    assert.ok(sql.includes(`select is(public.diag_cap_level(1, 5, true), 3, 'cap: first');`));
    assert.ok(sql.includes(`select is(public.diag_should_stop_skill('reading', 5, 0.9, 3), true, 'stop: reading max');`));
  });
});

test('accepts snake_case keys and rejects malformed fixtures', () => {
  withTmp(({ fx, out, env }) => {
    const data = { cap: [{ name: 'later', current: 2, suggested: 4, first_applied: false, expected: 3 }] };
    writeFileSync(fx, JSON.stringify(data));
    assert.equal(run([], env).status, 0);
    const sql = readFileSync(out, 'utf8');
    assert.ok(sql.includes('public.diag_cap_level(2, 4, false), 3'));
    assert.ok(!sql.includes('diag_posteriors'));

    writeFileSync(fx, JSON.stringify({ confidence: [{ name: 'bad', sd: 0.4, n: 6, rapidShare: 0, expected: 'very high' }] }));
    const bad = run([], env);
    assert.notEqual(bad.status, 0);
    assert.match(bad.stderr, /unknown confidence/);

    writeFileSync(fx, JSON.stringify({ stop: [{ name: 'nan', skill: 'grammar', n: 4.5, sd: 0.4, bankLeft: 1, expected: true }] }));
    assert.notEqual(run([], env).status, 0);
  });
});

test('the committed diagnostic_engine.test.sql is in sync', { skip: !existsSync(fixtures) && 'engine.fixtures.json not present yet' }, () => {
  assert.equal(run(['--check'], {}).status, 0);
});
