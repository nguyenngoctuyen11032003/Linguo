import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const script = join(root, 'scripts', 'sync-grading-fixtures.mjs');
const fixtures = join(root, 'packages', 'shared', 'src', 'content', 'grading.fixtures.json');

const run = (args, env) => spawnSync(process.execPath, [script, ...args], { env: { ...process.env, ...env }, encoding: 'utf8' });

test('--check passes after generation and fails after a fixture changes', () => {
  const dir = mkdtempSync(join(tmpdir(), 'grading-fixtures-'));
  try {
    const fx = join(dir, 'fixtures.json');
    const out = join(dir, 'grading.test.sql');
    const data = JSON.parse(readFileSync(fixtures, 'utf8'));
    writeFileSync(fx, JSON.stringify(data));
    const env = { GRADING_FIXTURES: fx, GRADING_OUT: out };

    assert.equal(run([], env).status, 0);
    const sql = readFileSync(out, 'utf8');
    assert.match(sql, /^-- GENERATED by scripts\/sync-grading-fixtures\.mjs/);
    assert.match(sql, new RegExp(`select plan\\(${data.normalize.length + data.grade.length}\\);`));
    assert.match(sql, /public\.grade_exercise\('mcq', '\{"correct_option_id":"b"\}'::jsonb, '\{"punctuation":"ignore"/);
    assert.equal(run(['--check'], env).status, 0);

    data.normalize[0].expected = 'changed';
    writeFileSync(fx, JSON.stringify(data));
    const check = run(['--check'], env);
    assert.equal(check.status, 1);
    assert.match(check.stderr, /out of date/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('the committed grading.test.sql is in sync', () => {
  assert.equal(run(['--check'], {}).status, 0);
});

test('rubric is merged over the default and score follows the verdict', () => {
  const dir = mkdtempSync(join(tmpdir(), 'grading-fixtures-'));
  try {
    const fx = join(dir, 'fixtures.json');
    const out = join(dir, 'grading.test.sql');
    writeFileSync(
      fx,
      JSON.stringify({
        normalize: [{ name: "it's", lang: 'en', rubric: { punctuation: 'strict' }, input: "It's", expected: "it's" }],
        grade: [
          {
            name: 'typo',
            type: 'translate',
            lang: 'en',
            rubric: { typo_tolerance: 1 },
            answer: { accepted: ['teacher'] },
            response: { text: 'teachr' },
            expected: { verdict: 'almost', error_tags: ['typo'], feedback_vi: null },
          },
        ],
      }),
    );
    assert.equal(run([], { GRADING_FIXTURES: fx, GRADING_OUT: out }).status, 0);
    const sql = readFileSync(out, 'utf8');
    assert.ok(sql.includes(`public.grading_normalize('It''s', 'en', '{"punctuation":"strict","diacritics":"strict","ko_spacing":"lenient","typo_tolerance":0,"expand_contractions":true}'::jsonb), 'it''s', 'normalize: it''s');`));
    assert.ok(sql.includes(`'{"verdict":"almost","score":0.8,"error_tags":["typo"],"feedback_vi":null}'::jsonb, 'grade: typo');`));
    assert.ok(sql.includes('"typo_tolerance":1'));
    assert.ok(sql.includes(`'[]'::jsonb, 'en'`));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('invisible characters are written as U& escapes', () => {
  const dir = mkdtempSync(join(tmpdir(), 'grading-fixtures-'));
  try {
    const fx = join(dir, 'fixtures.json');
    const out = join(dir, 'grading.test.sql');
    const bom = String.fromCodePoint(0xfeff);
    const nbsp = String.fromCodePoint(0xa0);
    writeFileSync(
      fx,
      JSON.stringify({
        normalize: [{ name: 'bom', lang: 'en', rubric: {}, input: `${bom}it's\\x${nbsp}`, expected: "it's" }],
        grade: [],
      }),
    );
    assert.equal(run([], { GRADING_FIXTURES: fx, GRADING_OUT: out }).status, 0);
    const sql = readFileSync(out, 'utf8');
    assert.ok(sql.includes(String.raw`public.grading_normalize(U&'\FEFFit''s\\x\00A0', 'en'`));
    assert.ok(!sql.includes(bom) && !sql.includes(nbsp));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
