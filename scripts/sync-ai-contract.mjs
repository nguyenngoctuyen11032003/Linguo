#!/usr/bin/env node
// Copies the ai-tutor request/response contract (packages/shared/src/ai/contract.ts) verbatim into
// supabase/functions/_shared/ai-contract.ts so the Edge Function (Deno) and the web app validate with the
// same zod schemas (spec 5 §2). In Deno, `zod` is resolved by supabase/functions/deno.json.
// Usage: node scripts/sync-ai-contract.mjs [--check]
// AI_CONTRACT_SRC / AI_CONTRACT_OUT override the input and output paths (used by the tests).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = process.env.AI_CONTRACT_SRC || join(root, 'packages', 'shared', 'src', 'ai', 'contract.ts');
const OUT = process.env.AI_CONTRACT_OUT || join(root, 'supabase', 'functions', '_shared', 'ai-contract.ts');

const source = readFileSync(SRC, 'utf8').replaceAll('\r\n', '\n');
// Only `zod` resolves on both sides (pnpm workspace / deno.json import map).
for (const m of source.matchAll(/^\s*(?:import|export)\b[^;]*?\bfrom\s+['"]([^'"]+)['"]/gm)) {
  if (m[1] !== 'zod') {
    console.error(`::error::packages/shared/src/ai/contract.ts may import only 'zod' (found '${m[1]}').`);
    process.exit(1);
  }
}

const generated = [
  '// GENERATED by scripts/sync-ai-contract.mjs from packages/shared/src/ai/contract.ts.',
  '// Do not edit by hand: run `pnpm ai:contract`.',
  '',
  source.endsWith('\n') ? source : `${source}\n`,
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replaceAll('\r\n', '\n') : '';
  if (current !== generated) {
    console.error('::error::supabase/functions/_shared/ai-contract.ts is out of date. Run `pnpm ai:contract` and commit.');
    process.exit(1);
  }
  console.log('AI contract in sync.');
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, generated);
  console.log(`Wrote ${OUT}.`);
}
