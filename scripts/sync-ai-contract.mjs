#!/usr/bin/env node
// Copies the ai-tutor request/response contract (packages/shared/src/ai/contract.ts) and the role-play scenario
// catalog (packages/shared/src/ai/roleplay-catalog.ts) verbatim into supabase/functions/_shared/ so the Edge
// Function (Deno) and the web app validate with the same zod schemas and scenarios (spec 5 §2). In Deno, `zod` is
// resolved by supabase/functions/deno.json.
// Usage: node scripts/sync-ai-contract.mjs [--check]
// AI_CONTRACT_SRC / AI_CONTRACT_OUT override the contract paths (used by the tests); when they are set the
// catalog is only synced if ROLEPLAY_CATALOG_SRC / ROLEPLAY_CATALOG_OUT are set too.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const overridden = Boolean(process.env.AI_CONTRACT_SRC || process.env.AI_CONTRACT_OUT);

/** `allowedImports`: module specifiers the file may import (only `zod` resolves on both sides; the catalog imports nothing). */
const targets = [
  {
    src: process.env.AI_CONTRACT_SRC || join(root, 'packages', 'shared', 'src', 'ai', 'contract.ts'),
    out: process.env.AI_CONTRACT_OUT || join(root, 'supabase', 'functions', '_shared', 'ai-contract.ts'),
    from: 'packages/shared/src/ai/contract.ts',
    to: 'supabase/functions/_shared/ai-contract.ts',
    allowedImports: ['zod'],
  },
];
if (!overridden || process.env.ROLEPLAY_CATALOG_SRC) {
  targets.push({
    src: process.env.ROLEPLAY_CATALOG_SRC || join(root, 'packages', 'shared', 'src', 'ai', 'roleplay-catalog.ts'),
    out: process.env.ROLEPLAY_CATALOG_OUT || join(root, 'supabase', 'functions', '_shared', 'roleplay-catalog.ts'),
    from: 'packages/shared/src/ai/roleplay-catalog.ts',
    to: 'supabase/functions/_shared/roleplay-catalog.ts',
    allowedImports: [],
  });
}

const check = process.argv.includes('--check');
let failed = false;

for (const t of targets) {
  const source = readFileSync(t.src, 'utf8').replaceAll('\r\n', '\n');
  let bad = false;
  for (const m of source.matchAll(/^\s*(?:import|export)\b[^;]*?\bfrom\s+['"]([^'"]+)['"]/gm)) {
    if (!t.allowedImports.includes(m[1])) {
      const only = t.allowedImports.length ? `only ${t.allowedImports.map((i) => `'${i}'`).join(', ')}` : 'nothing';
      console.error(`::error::${t.from} may import ${only} (found '${m[1]}').`);
      bad = true;
    }
  }
  if (bad) process.exit(1);

  const generated = [
    `// GENERATED by scripts/sync-ai-contract.mjs from ${t.from}.`,
    '// Do not edit by hand: run `pnpm ai:contract`.',
    '',
    source.endsWith('\n') ? source : `${source}\n`,
  ].join('\n');

  if (check) {
    const current = existsSync(t.out) ? readFileSync(t.out, 'utf8').replaceAll('\r\n', '\n') : '';
    if (current !== generated) {
      console.error(`::error::${t.to} is out of date. Run \`pnpm ai:contract\` and commit.`);
      failed = true;
    }
  } else {
    mkdirSync(dirname(t.out), { recursive: true });
    writeFileSync(t.out, generated);
    console.log(`Wrote ${t.out}.`);
  }
}

if (check) {
  if (failed) process.exit(1);
  console.log('AI contract in sync.');
}
