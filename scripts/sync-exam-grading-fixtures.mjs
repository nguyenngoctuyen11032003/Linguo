#!/usr/bin/env node
// Generates supabase/tests/exam_grading.test.sql from packages/shared/src/exam/grading.fixtures.json so that
// the SQL short_text grader (public.exam_normalize_text as used by public.exam_build_result) and
// gradeExamAnswer / normalizeExamText in packages/shared/src/exam/grading.ts agree case for case.
// Usage: node scripts/sync-exam-grading-fixtures.mjs [--check]
// EXAM_GRADING_FIXTURES / EXAM_GRADING_OUT override the input and output paths (used by the tests).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FIXTURES = process.env.EXAM_GRADING_FIXTURES || join(root, 'packages', 'shared', 'src', 'exam', 'grading.fixtures.json');
const OUT = process.env.EXAM_GRADING_OUT || join(root, 'supabase', 'tests', 'exam_grading.test.sql');

const fixtures = JSON.parse(readFileSync(FIXTURES, 'utf8'));
if (!Array.isArray(fixtures)) throw new Error('Exam grading fixtures must be an array of { input, accepted, correct }');

// Control, space-like, combining and conjoining-jamo (NFD Hangul) chars are written as U&'' escapes so
// the generated SQL survives editors that strip or normalise them.
const ESCAPED_RANGES = [
  [0x0, 0x1f],
  [0x7f, 0xa0],
  [0xad, 0xad],
  [0x300, 0x36f],
  [0x1100, 0x11ff],
  [0x1680, 0x1680],
  [0x2000, 0x200f],
  [0x2028, 0x202f],
  [0x205f, 0x206f],
  [0x3000, 0x3000],
  [0xfeff, 0xfeff],
];
const ESCAPED = new RegExp(`[${ESCAPED_RANGES.map(([a, b]) => `\\u{${a.toString(16)}}-\\u{${b.toString(16)}}`).join('')}]`, 'gu');
const lit = (s) => {
  const str = String(s).replaceAll("'", "''");
  if (!str.match(ESCAPED)) return `'${str}'`;
  const escaped = str
    .replaceAll('\\', '\\\\')
    .replace(ESCAPED, (ch) => {
      const cp = ch.codePointAt(0);
      return cp > 0xffff ? `\\+${cp.toString(16).toUpperCase().padStart(6, '0')}` : `\\${cp.toString(16).toUpperCase().padStart(4, '0')}`;
    });
  return `U&'${escaped}'`;
};
// Labels are ASCII-only (JSON with \u escapes) so the test output is readable in any terminal.
const asciiJson = (v) => JSON.stringify(v).replace(/[^\x20-\x7e]/gu, (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`);

const asserts = fixtures.map((c, i) => {
  if (typeof c.input !== 'string') throw new Error(`Fixture #${i + 1}: input must be a string`);
  if (!Array.isArray(c.accepted) || c.accepted.length === 0 || c.accepted.some((a) => typeof a !== 'string')) {
    throw new Error(`Fixture #${i + 1}: accepted must be a non-empty string array`);
  }
  if (typeof c.correct !== 'boolean') throw new Error(`Fixture #${i + 1}: correct must be a boolean`);
  const accepted = `array[${c.accepted.map(lit).join(', ')}]::text[]`;
  // Same predicate as the short_text branch of public.exam_build_result.
  const graded =
    `(public.exam_normalize_text(${lit(c.input)}) <> '' and exists (select 1 from unnest(${accepted}) as acc(t) ` +
    `where public.exam_normalize_text(acc.t) = public.exam_normalize_text(${lit(c.input)})))`;
  const label = lit(`short_text #${i + 1}: ${asciiJson(c.input)} vs ${asciiJson(c.accepted)}`);
  return `select is(${graded}, ${c.correct}, ${label});`;
});

const sql = [
  '-- GENERATED by scripts/sync-exam-grading-fixtures.mjs from packages/shared/src/exam/grading.fixtures.json.',
  '-- Do not edit by hand: run `pnpm fixtures:exam`.',
  'begin;',
  'create extension if not exists pgtap with schema extensions;',
  `select plan(${asserts.length});`,
  ...asserts,
  'select * from finish();',
  'rollback;',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replaceAll('\r\n', '\n') : '';
  if (current !== sql) {
    console.error('::error::supabase/tests/exam_grading.test.sql is out of date. Run `pnpm fixtures:exam` and commit.');
    process.exit(1);
  }
  console.log('Exam grading fixtures in sync.');
} else {
  writeFileSync(OUT, sql);
  console.log(`Wrote ${OUT} (${asserts.length} assertions).`);
}
