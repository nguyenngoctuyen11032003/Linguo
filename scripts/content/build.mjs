// Builds the import bundle (packages/shared/src/content/bundle.ts) from checked content and renders
// supabase/seed.sql. Output is deterministic: rows sorted by key, JSON with sorted object keys.
import { BUNDLE_VERSION, bundleSchema } from '@linguo/shared';
import { canonicalJson, hashRow, sha256Hex } from './hash.mjs';
import { contentId } from './ids.mjs';
import { effectiveStatus, formatIssues, indexContent } from './load.mjs';

export const SEED_HEADER = '-- GENERATED by scripts/content-import.mjs';
const DOLLAR_TAG = '$bundle$';

const byKey = (a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0);

/**
 * Review fields of a row. Sources (per entry) and learning items (per items file) may omit
 * `status`: demo rows then import as `published` (visible but labelled); check.mjs rejects a
 * non-demo row without an explicit status, so reaching the throw means the check was skipped.
 */
function review(data, isDemo) {
  const status = effectiveStatus(data.status, isDemo);
  if (!status) throw new Error(`${data.key ?? 'row'}: non-demo content needs an explicit status (run --check)`);
  return {
    status,
    is_demo: isDemo,
    reviewed_by: data.reviewed_by ?? null,
    reviewed_at: data.reviewed_at ?? null,
  };
}

/** Exercise types whose options are picked by id: their order must not hint at the answer. */
const SHUFFLED_OPTION_TYPES = new Set(['mcq', 'listen']);

/**
 * Deterministic Fisher-Yates shuffle seeded by `seed` (each draw is a slice of sha256(seed#i)), so the same
 * content always builds the same bundle while authors never have to vary where the correct option sits.
 */
export function seededShuffle(list, seed) {
  const out = [...list];
  for (let i = out.length - 1; i > 0; i--) {
    const draw = Number.parseInt(sha256Hex(`${seed}#${i}`).slice(0, 12), 16) / 2 ** 48;
    const j = Math.floor(draw * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** The exercise prompt as served: mcq/listen options shuffled by the exercise key (authored YAML order is ignored). */
export function bundlePrompt(ex) {
  if (!SHUFFLED_OPTION_TYPES.has(ex.type) || !Array.isArray(ex.prompt?.options)) return ex.prompt;
  return { ...ex.prompt, options: seededShuffle(ex.prompt.options, ex.key) };
}

function withHash(row, children) {
  return { ...row, content_hash: hashRow(row, children) };
}

/** @param loaded result of loadContent() that passed checkContent() */
export function buildBundle(loaded, { gitSha = null } = {}) {
  const { sources, items, programs, units, lessons } = indexContent(loaded.files);

  const bundle = {
    bundle_version: BUNDLE_VERSION,
    git_sha: gitSha,
    sources: sources
      .map(({ data: s }) =>
        withHash({
          id: contentId(s.key),
          key: s.key,
          title: s.title,
          author_or_org: s.author_or_org,
          url: s.url,
          license: s.license,
          attribution_required: s.attribution_required,
          ...review(s, s.demo),
        }),
      )
      .sort(byKey),
    programs: programs
      .map(({ data: p }) =>
        withHash({
          id: contentId(p.key),
          key: p.key,
          source_id: contentId(p.source),
          language_code: p.language,
          title: p.title,
          description: p.description,
          kind: p.kind,
          goal_types: p.goal_types,
          level_from: p.level_from,
          level_to: p.level_to,
          order_index: p.order_index,
          ...review(p, p.demo),
        }),
      )
      .sort(byKey),
    units: units
      .map(({ data: u, program }) =>
        withHash({
          id: contentId(u.key),
          key: u.key,
          source_id: contentId(program.data.source),
          program_id: contentId(program.data.key),
          order_index: u.order_index,
          title: u.title,
          ...review(u, u.demo),
        }),
      )
      .sort(byKey),
    lessons: [],
    lesson_prerequisites: [],
    learning_items: items
      .map(({ data: i, lang, source, demo, review: itemReview }) =>
        withHash({
          id: contentId(i.key),
          key: i.key,
          source_id: contentId(source),
          language_code: lang,
          item_type: i.type,
          level_code: i.level,
          difficulty: i.difficulty,
          skill_tags: i.skill_tags,
          front: i.front,
          back: i.back,
          audio_path: i.audio_path,
          ...review({ key: i.key, ...itemReview }, demo),
        }),
      )
      .sort(byKey),
    lesson_items: [],
    exercises: [],
  };

  for (const { data: l, unit, program, lang } of [...lessons].sort((a, b) => byKey(a.data, b.data))) {
    const lessonId = contentId(l.key);
    const sourceId = contentId(program.data.source);
    const lessonReview = review(l, l.demo);

    const exercises = l.exercises.map((ex, index) =>
      withHash({
        id: contentId(ex.key),
        key: ex.key,
        source_id: sourceId,
        lesson_id: lessonId,
        item_id: ex.item ? contentId(ex.item) : null,
        order_index: index,
        exercise_type: ex.type,
        stage: ex.stage,
        answer_lang: ex.answer_lang,
        difficulty: ex.difficulty,
        prompt: bundlePrompt(ex),
        ...lessonReview,
        key_data: {
          answer_key: ex.answer,
          rubric: ex.rubric,
          known_wrong: ex.known_wrong,
          explanation: ex.explanation,
          display_answer: ex.display_answer,
        },
      }),
    );
    const prerequisites = [...l.prerequisites].sort();
    const links = l.items.map((link, position) => ({ item: link.item, role: link.role, position }));

    bundle.lessons.push(
      withHash(
        {
          id: lessonId,
          key: l.key,
          source_id: sourceId,
          unit_id: contentId(unit.data.key),
          language_code: lang,
          level_code: l.level,
          order_index: l.order_index,
          title: l.title,
          objectives: l.objectives,
          body: l.body,
          estimated_minutes: l.estimated_minutes,
          skills: l.skills,
          ...lessonReview,
        },
        // A change in any child row changes the lesson hash (plan decision 2).
        { exercises: exercises.map((e) => e.content_hash), items: links, prerequisites },
      ),
    );
    for (const pre of prerequisites) {
      bundle.lesson_prerequisites.push({ lesson_id: lessonId, prerequisite_lesson_id: contentId(pre) });
    }
    for (const link of links) {
      bundle.lesson_items.push({ lesson_id: lessonId, item_id: contentId(link.item), position: link.position, role: link.role });
    }
    bundle.exercises.push(...exercises);
  }
  bundle.exercises.sort(byKey);

  const parsed = bundleSchema.safeParse(bundle);
  if (!parsed.success) throw new Error(`Bundle does not match bundleSchema:\n${formatIssues(parsed.error).join('\n')}`);
  return bundle;
}

/** supabase/seed.sql contents: one dollar-quoted import_bundle call. */
export function renderSeedSql(bundle) {
  const json = canonicalJson(bundle, 2);
  if (json.includes(DOLLAR_TAG)) throw new Error(`Content must not contain the text ${DOLLAR_TAG}`);
  return [
    `${SEED_HEADER} from content/. Do not edit by hand: run \`pnpm content:build\`.`,
    '-- Loaded by `supabase db reset` ([db.seed] in supabase/config.toml); never run against the hosted DB',
    '-- except through `pnpm content:push` (workflow content-publish.yml).',
    `select content_private.import_bundle(${DOLLAR_TAG}${json}${DOLLAR_TAG}::jsonb);`,
    '',
  ].join('\n');
}
