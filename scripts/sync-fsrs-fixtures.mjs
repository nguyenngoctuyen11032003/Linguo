#!/usr/bin/env node
// Generates supabase/tests/review_fsrs.test.sql from packages/shared/src/review/fsrs.fixtures.json so
// that public.srs_next (SQL) is verified against the pinned ts-fsrs. Each step is fed the previous
// step's expected card (not the SQL result), so one mismatch does not cascade through a case.
// state/step/scheduled_days/interval_minutes/lapse/due_at must match exactly; stability and
// difficulty within 1e-6. Fixtures use tz UTC, so due_at for day intervals is UTC midnight of
// (review date + scheduled_days) and minute steps are review time + interval_minutes.
// Usage: node scripts/sync-fsrs-fixtures.mjs [--check]
// FSRS_FIXTURES / FSRS_OUT override the input and output paths (used by the tests).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FIXTURES = process.env.FSRS_FIXTURES || join(root, 'packages', 'shared', 'src', 'review', 'fsrs.fixtures.json');
const OUT = process.env.FSRS_OUT || join(root, 'supabase', 'tests', 'review_fsrs.test.sql');

const DAY = 86_400_000;
const fixtures = JSON.parse(readFileSync(FIXTURES, 'utf8'));
const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;
const ts = (iso) => `${lit(iso)}::timestamptz`;
const num = (n) => {
  if (!Number.isFinite(n)) throw new Error(`Not a finite number: ${n}`);
  return String(n);
};

const calls = [];
const asserts = [];
let id = 0;
for (const c of fixtures.cases) {
  if (c.tz !== 'UTC') throw new Error(`Case "${c.name}": only tz UTC is supported (snapping is tested by hand)`);
  let card = { state: 'new', step: 0, stability: 0, difficulty: 0, last: null };
  c.steps.forEach((s, i) => {
    id++;
    const e = s.expected;
    const label = `${c.name} #${i + 1}`;
    const last = card.last === null ? 'null::timestamptz' : ts(card.last);
    calls.push(
      `(${id}, ${lit(label)}, public.srs_next(${lit(card.state)}, ${card.step}::smallint, ${num(card.stability)}::double precision, ${num(card.difficulty)}::double precision, ${last}, ${s.rating}::smallint, ${ts(s.at)}, ${lit(c.tz)}))`,
    );
    const at = Date.parse(s.at);
    const due =
      e.scheduled_days >= 1
        ? new Date(Math.floor(at / DAY) * DAY + e.scheduled_days * DAY)
        : new Date(at + e.interval_minutes * 60_000);
    const sel = (expr) => `(select ${expr} from fsrs_results where id = ${id})`;
    const is = (expr, expected, field) => asserts.push(`select is(${sel(expr)}, ${expected}, ${lit(`${label}: ${field}`)});`);
    const near = (field, expected) =>
      asserts.push(
        `select ok(${sel(`abs((r->>'${field}')::double precision - ${num(expected)}) < 1e-6`)}, ${lit(`${label}: ${field}`)});`,
      );
    is(`r->>'state'`, lit(e.state), 'state');
    is(`(r->>'step')::int`, e.step, 'step');
    near('stability', e.stability);
    near('difficulty', e.difficulty);
    is(`(r->>'scheduled_days')::int`, e.scheduled_days, 'scheduled_days');
    is(`(r->>'interval_minutes')::int`, e.interval_minutes, 'interval_minutes');
    is(`(r->>'lapse')::boolean`, e.lapse, 'lapse');
    is(`(r->>'due_at')::timestamptz`, ts(due.toISOString()), 'due_at');
    card = { state: e.state, step: e.step, stability: e.stability, difficulty: e.difficulty, last: s.at };
  });
}

const sql = [
  '-- GENERATED by scripts/sync-fsrs-fixtures.mjs from packages/shared/src/review/fsrs.fixtures.json.',
  '-- Do not edit by hand: run `pnpm fixtures:fsrs`.',
  `-- ts-fsrs ${fixtures.ts_fsrs_version}, ${fixtures.cases.length} cases, ${id} steps.`,
  'begin;',
  'create extension if not exists pgtap with schema extensions;',
  `select plan(${asserts.length});`,
  'create temp table fsrs_results (id int primary key, label text not null, r jsonb) on commit drop;',
  'insert into fsrs_results (id, label, r) values',
  calls.map((c, i) => `  ${c}${i === calls.length - 1 ? ';' : ','}`).join('\n'),
  ...asserts,
  'select * from finish();',
  'rollback;',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replaceAll('\r\n', '\n') : '';
  if (current !== sql) {
    console.error('::error::supabase/tests/review_fsrs.test.sql is out of date. Run `pnpm fixtures:fsrs` and commit.');
    process.exit(1);
  }
  console.log('FSRS fixtures in sync.');
} else {
  writeFileSync(OUT, sql);
  console.log(`Wrote ${OUT} (${asserts.length} assertions).`);
}
