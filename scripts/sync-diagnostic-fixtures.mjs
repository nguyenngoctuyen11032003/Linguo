#!/usr/bin/env node
// Generates supabase/tests/diagnostic_engine.test.sql from packages/shared/src/diagnostic/engine.fixtures.json
// so that the SQL engine (public.diag_*) and packages/shared/src/diagnostic/engine.ts are verified against the
// same cases. Floats (EAP mean/sd) must match within 1e-6; levels, ranges, confidence, suggestions, caps and
// stop decisions exactly.
// Usage: node scripts/sync-diagnostic-fixtures.mjs [--check]
// DIAGNOSTIC_FIXTURES / DIAGNOSTIC_OUT override the input and output paths (used by the tests).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FIXTURES =
  process.env.DIAGNOSTIC_FIXTURES || join(root, 'packages', 'shared', 'src', 'diagnostic', 'engine.fixtures.json');
const OUT = process.env.DIAGNOSTIC_OUT || join(root, 'supabase', 'tests', 'diagnostic_engine.test.sql');
const TOLERANCE = '1e-6';

const fixtures = JSON.parse(readFileSync(FIXTURES, 'utf8'));
const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;
const num = (n) => {
  if (typeof n !== 'number' || !Number.isFinite(n)) throw new Error(`Not a finite number: ${n}`);
  return String(n);
};
const int = (n) => {
  if (!Number.isInteger(n)) throw new Error(`Not an integer: ${n}`);
  return String(n);
};
const bool = (b) => {
  if (typeof b !== 'boolean') throw new Error(`Not a boolean: ${b}`);
  return String(b);
};
const arr = (values, fmt, type) => `array[${values.map(fmt).join(', ')}]::${type}[]`;
// Fixture keys follow the TS engine (camelCase); snake_case is accepted too.
const field = (c, camel, snake) => {
  if (camel in c) return c[camel];
  if (snake in c) return c[snake];
  throw new Error(`Fixture "${c.name}": missing ${camel}`);
};
const CONFIDENCE = new Set(['low', 'medium', 'high']);
const SKILLS = new Set(['vocabulary', 'grammar', 'reading']);

const asserts = [];
const assert = (sql) => asserts.push(sql);
const label = (group, c) => lit(`${group}: ${c.name}`);

// posterior → EAP mean/sd, conservative level, range.
const posteriorRows = [];
(fixtures.posterior ?? []).forEach((c, i) => {
  const id = i + 1;
  const answers = c.answers ?? [];
  posteriorRows.push(
    `(${id}, public.diag_posterior(${num(c.prior.mean)}, ${num(c.prior.sd)}, ${arr(answers.map((a) => a.b), num, 'double precision')}, ${arr(answers.map((a) => a.options), int, 'integer')}, ${arr(answers.map((a) => a.correct), bool, 'boolean')}))`,
  );
  const sel = (expr) => `(select ${expr} from diag_posteriors where id = ${id})`;
  const name = (what) => lit(`posterior: ${c.name}: ${what}`);
  const e = c.expected;
  for (const k of ['mean', 'sd']) {
    assert(
      `select ok(${sel(`abs((public.diag_eap(w)->>'${k}')::double precision - ${num(e[k])}) < ${TOLERANCE}`)}, ${name(k)});`,
    );
  }
  assert(`select is(${sel('public.diag_conservative_level(w)')}, ${int(e.level)}, ${name('level')});`);
  assert(
    `select is(${sel('public.diag_level_range(w)')}, '{"low": ${int(e.range.low)}, "high": ${int(e.range.high)}}'::jsonb, ${name('range')});`,
  );
});

for (const c of fixtures.confidence ?? []) {
  if (!CONFIDENCE.has(c.expected)) throw new Error(`Fixture "${c.name}": unknown confidence ${c.expected}`);
  assert(
    `select is(public.diag_confidence(${num(c.sd)}, ${int(c.n)}, ${num(field(c, 'rapidShare', 'rapid_share'))}), ${lit(c.expected)}, ${label('confidence', c)});`,
  );
}

for (const c of fixtures.suggest ?? []) {
  for (const s of c.skills) {
    if (!CONFIDENCE.has(s.confidence)) throw new Error(`Fixture "${c.name}": unknown confidence ${s.confidence}`);
  }
  const expected = c.expected === null ? 'null::integer' : int(c.expected);
  assert(
    `select is(public.diag_suggest_level(${arr(c.skills.map((s) => s.level), int, 'integer')}, ${arr(c.skills.map((s) => s.confidence), lit, 'text')}), ${expected}, ${label('suggest', c)});`,
  );
}

for (const c of fixtures.cap ?? []) {
  assert(
    `select is(public.diag_cap_level(${int(c.current)}, ${int(c.suggested)}, ${bool(field(c, 'firstApplied', 'first_applied'))}), ${int(c.expected)}, ${label('cap', c)});`,
  );
}

for (const c of fixtures.stop ?? []) {
  if (!SKILLS.has(c.skill)) throw new Error(`Fixture "${c.name}": unknown skill ${c.skill}`);
  assert(
    `select is(public.diag_should_stop_skill(${lit(c.skill)}, ${int(c.n)}, ${num(c.sd)}, ${int(field(c, 'bankLeft', 'bank_left'))}), ${bool(c.expected)}, ${label('stop', c)});`,
  );
}

const sql = [
  '-- GENERATED by scripts/sync-diagnostic-fixtures.mjs from packages/shared/src/diagnostic/engine.fixtures.json.',
  '-- Do not edit by hand: run `pnpm fixtures:diagnostic`.',
  'begin;',
  'create extension if not exists pgtap with schema extensions;',
  `select plan(${asserts.length});`,
  ...(posteriorRows.length
    ? [
        'create temp table diag_posteriors (id int primary key, w double precision[] not null) on commit drop;',
        'insert into diag_posteriors (id, w) values',
        posteriorRows.map((r, i) => `  ${r}${i === posteriorRows.length - 1 ? ';' : ','}`).join('\n'),
      ]
    : []),
  ...asserts,
  'select * from finish();',
  'rollback;',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replaceAll('\r\n', '\n') : '';
  if (current !== sql) {
    console.error(
      '::error::supabase/tests/diagnostic_engine.test.sql is out of date. Run `pnpm fixtures:diagnostic` and commit.',
    );
    process.exit(1);
  }
  console.log('Diagnostic fixtures in sync.');
} else {
  writeFileSync(OUT, sql);
  console.log(`Wrote ${OUT} (${asserts.length} assertions).`);
}
